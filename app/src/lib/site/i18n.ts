export const DICTS: Record<Lang, Dict> = { en, ru, vi };

export function dict(lang: Lang): Dict {
  return DICTS[lang] ?? DICTS[DEFAULT_LANG];
}

/** Translates the free-text price labels stored on menu items ("Thời giá", "Đang cập nhật", "Liên hệ"). */
export function priceLabel(priceText: string, lang: Lang): string {
  const p = dict(lang).price;
  const t = priceText.trim().toLowerCase();
  if (t === "thời giá") return p.market;
  if (t === "đang cập nhật") return p.updating;
  if (t === "liên hệ") return p.contact;
  return priceText;
}

