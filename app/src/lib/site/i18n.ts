/**
 * Public website translations. English is the default (most Lumia Apartment
 * guests are foreign — largely Russian-speaking); Vietnamese and Russian are
 * one tap away in the header. Placeholders use {name} and are filled by fmt().
 */
export const LANGS = ["en", "ru", "vi"] as const;
export type Lang = (typeof LANGS)[number];
export const DEFAULT_LANG: Lang = "en";
export const LANG_COOKIE = "lang";
export const LANG_LABEL: Record<Lang, string> = { en: "EN", ru: "RU", vi: "VI" };

export function toLang(v: unknown): Lang {
  return LANGS.includes(v as Lang) ? (v as Lang) : DEFAULT_LANG;
}

export function fmt(s: string, vars: Record<string, string | number>): string {
  return s.replace(/\{(\w+)\}/g, (_, k) => (k in vars ? String(vars[k]) : `{${k}}`));
}

